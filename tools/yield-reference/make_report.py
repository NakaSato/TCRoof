"""Builds tools/yield-reference/RESULTS.md from the engine outputs (all numbers computed, none typed)."""
import json, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import pvlib
import reference_engine as R

S = json.loads((HERE / "results-summary.json").read_text())
by = {r["scenario"]: r for r in S}
L = []
w = L.append
w("# Reference yield results — Znshine 570 W + Growatt MAX\n")
w(f"Generated by `tools/yield-reference/make_report.py` from `reference_engine.py` (pvlib {pvlib.__version__}). Golden values for the Swift port.\n")
w("""## Method and assumptions

| Item | Value |
|---|---|
| Meteo | PVGIS 5.3 TMY (PVGIS-ERA5) per site, hourly. `GSA` scenarios scale GHI/DNI/DHI to the Global Solar Atlas (Solargis) annual GHI |
| Hour convention | TMY GHI/DHI are averages of the hour starting at the timestamp. Sun geometry = mean cos θz over the sunlit part of the hour, azimuth at its middle; DNI recomputed as (GHI − DHI)/mean cos θz. This reproduces PVGIS's own east/west ratios (E/S 0.968 vs 0.971, W/S 0.956 vs 0.958 at 10°, Bangkok) |
| Transposition | Perez 1990, albedo 0.20 |
| IAM | ASHRAE b₀ = 0.05; Marion integration for diffuse/ground |
| Soiling | 3 % |
| Cell temperature | PVsyst; Uc = 20 W/m²K (railed roof), 29 (free-standing ground); Uv = 0; α = 0.9 |
| Module | Znshine ZXM7-UHLDD144-570, PVsyst one-diode fitted from datasheet (Rs 0.230 Ω, γ 0.980, μγ −0.00019/K, Rsh 300 Ω) |
| Quality / LID / mismatch | 0 % / 1 % / 1 % |
| DC ohmic | 1.5 % at STC (scales with I and 1/V) |
| Inverter | Growatt datasheet fit (η_max, η_euro, peak at 40 % load), clipping at AC nominal, MPPT current limit |
| AC ohmic / unavailability / night | 0.5 % at nominal / 1 % / 1 W |
| Shading | Per face: annual % from the survey, plus optional horizon profile (beam cut below it, sky diffuse reduced by the blocked share). Ground rows: unlimited-sheds row-to-row model |
| Bifacial | pvlib infinite-sheds; φ 0.80, rear structure shading 5 %, rear mismatch 10 % |
| Ageing | PVsyst linear mid-year, 0.40 %/yr (Znshine warranty after year 1; LID covers the year-1 drop) |
| P50/P90 | PVsyst method; σ: climate 2 %, meteo 8 % (ERA5) or 5 % (Solargis-scaled), module model 1 %, quality 1 %, soiling+mismatch 1 %, inverter 0.5 %, unmodelled shading 2 %; RSS; degradation excluded |
""")

def row(r, label=None):
    d = r["config"]["design"]; p = r["probability"]; e = r["energies_kWh"]
    return (f"| {label or r['scenario']} | {r['p_nom_dc_kWp']:.2f} | {r['dc_ac_ratio']:.2f} | {e['E_grid']:,.0f} | "
            f"{r['specific_yield']:,.1f} | {r['PR']*100:.1f} % | {p['P90_1yr']:,} | {r['lifetime_kWh']:,} |")
hdr = "| Scenario | DC kWp | DC/AC | E_Grid yr 1 (P50) | kWh/kWp | PR | P90 1-yr | 25-yr total |\n|---|---|---|---|---|---|---|---|"

w("## 1. Bangkok reference designs (roof, 10°, south)\n")
w(hdr)
for k in ["60kW-ERA5", "60kW-GSA", "80kW-ERA5", "80kW-GSA", "125kW-ERA5", "125kW-GSA"]:
    w(row(by[k]))
r = by["60kW-ERA5"]; e = r["energies_kWh"]; h = r["hours"]
w(f"\n### Loss diagram — 60 kW, ERA5\n\n| Step | Change |\n|---|---|\n| GHI | {e['H_hor']:,.0f} kWh/m² |\n| GlobInc (POA) | {e['H_inc']:,.0f} kWh/m² |")
for n, v in r["loss_diagram"]:
    w(f"| {n} | {v:+.2f} % |")
w(f"| **E_Grid** | **{e['E_grid']:,.0f} kWh** |\n")
w(f"MPPT current limit active {h['current_limited']} h/yr, clipping {h['clipped']} h/yr, max DC {h['max_dc_kW']:.1f} kW, mean daytime cell {h['t_cell_mean_daylight']:.1f} °C, max {h['t_cell_max']:.1f} °C.\n")
w("| Month | GHI | POA | E_Grid kWh | PR |\n|---|---|---|---|---|")
for m in r["monthly"]:
    w(f"| {m['month']} | {m['GHI']} | {m['POA']} | {m['E_grid']:,.0f} | {m['PR']*100:.1f} % |")

w("\n## 2. Bifacial on a pitched metal roof\n")
w("Modules railed parallel to the roof; the rear side sees the roof sheet (sun rotated into the roof frame).\n")
w(hdr)
for k, lab in [("60kW-ERA5", "60 kW monofacial"), ("60kW-ERA5-bifacial-roof", "60 kW bifacial, albedo 0.30, standoff 0.12 m"),
               ("60kW-ERA5-bifacial-roof-albedo0.5-h0.20", "60 kW bifacial, albedo 0.50, standoff 0.20 m")]:
    w(row(by[k], lab))
g0, g1 = by["60kW-ERA5"]["energies_kWh"]["E_grid"], by["60kW-ERA5-bifacial-roof"]["energies_kWh"]["E_grid"]
w(f"\nRear gain on a railed metal roof is {100*(g1/g0-1):+.2f} % (infinite rows; array edges add a little). Treat it as 0–1 %.\n")

w("## 3. Ground mount\n")
gr = by["125kW-ERA5-ground-bifacial"]["rows"]
w(f"2-in-portrait tables (slant 4.58 m), 0.6 m clearance, Uc 29, grass albedo 0.20. Pitch from the no-shading 09:00–15:00 on 21 Dec rule: **{gr['pitch_m']} m, GCR {gr['gcr']}** at 15°.\n")
w(hdr)
for k, lab in [("125kW-ERA5-bifacial-roof", "125 kW roof, bifacial (reference)"), ("125kW-ERA5-ground-monofacial", "125 kW ground, monofacial"),
               ("125kW-ERA5-ground-bifacial", "125 kW ground, bifacial, grass"), ("125kW-ERA5-ground-bifacial-gravel0.4", "125 kW ground, bifacial, white gravel 0.4"),
               ("125kW-ERA5-ground-bifacial-tilt10", "125 kW ground, bifacial, 10°"), ("125kW-ERA5-ground-bifacial-tilt20", "125 kW ground, bifacial, 20°"),
               ("60kW-ERA5-ground-bifacial", "60 kW ground, bifacial, grass"), ("80kW-ERA5-ground-bifacial", "80 kW ground, bifacial, grass")]:
    w(row(by[k], lab))
gb = by["125kW-ERA5-ground-bifacial"]
w("\nLoss lines that differ from the roof (125 kW, grass, bifacial):\n\n| Step | Change |\n|---|---|")
for n, v in gb["loss_diagram"]:
    if n.startswith(("Transposition", "Shading", "Bifacial", "PV loss due to temperature", "Clipping")):
        w(f"| {n} | {v:+.2f} % |")
w(f"\nMean daytime cell temperature {gb['hours']['t_cell_mean_daylight']} °C (roof: {by['125kW-ERA5-bifacial-roof']['hours']['t_cell_mean_daylight']} °C). Clipping {gb['hours']['clipped']} h/yr.\n")
# pitch sensitivity
base = dict(lat=13.75, lon=100.50, azimuth=180, tilt=15, module_json="components/znshine-zxm7-uhldd144-570.json",
            meteo_csv="data/pvgis-tmy-era5-bangkok-13.75-100.50.csv",
            inverter_json="components/growatt-max-125ktl3-x-lv.json", design=R.StringDesign(14, 20),
            thermal=R.Thermal(u_c=29), uncertainty=R.Uncertainty(meteo_data=0.08))
w("Pitch vs bifacial gain (125 kW, grass, 15°):\n\n| Pitch | GCR | Shading | Rear gain | E_Grid mono | E_Grid bifacial | Clipped h |\n|---|---|---|---|---|---|---|")
for pitch in [gr["pitch_m"], 7.0, 8.0, 10.0]:
    rm = R.run(R.Scenario(name="m", rows=R.RowGeometry(pitch_m=pitch), **base))
    rb = R.run(R.Scenario(name="b", rows=R.RowGeometry(pitch_m=pitch), bifacial=R.Bifacial(enabled=True, frame="ground"), **base))
    shv = [b for a, b in rb["loss_diagram"] if a.startswith("Shading")][0]
    rg = [b for a, b in rb["loss_diagram"] if a.startswith("Bifacial")][0]
    w(f"| {pitch:.2f} m | {rb['rows']['gcr']:.2f} | {shv:+.2f} % | {rg:+.2f} % | {rm['energies_kWh']['E_grid']:,.0f} | {rb['energies_kWh']['E_grid']:,.0f} | {rb['hours']['clipped']} |")
w("\nLand per kWp grows with pitch (×1.75 from the rule pitch to 10 m). Ground arrays near farmland or unpaved roads often need 4–5 % soiling instead of 3 %.\n")

bm = HERE / "sites" / "banmi-faces-shading.json"
if bm.exists():
    w("## 4. Several orientations and shading — example: สถานีผลิตน้ำบ้านหมี่ (150.48 kWp, 125 kW, Solargis-scaled)\n")
    w("| Case | E_Grid | kWh/kWp | PR | vs A | Shading loss | P90 |\n|---|---|---|---|---|---|---|")
    for c in json.loads(bm.read_text()):
        w(f"| {c['case']}. {c['label']} | {c['E_grid']:,} | {c['sy']} | {c['PR']*100:.1f} % | {c['vsA']:+.1f} % | {c['shading']:+.2f} % | {c['P90']:,} |")
    w("\nPer face (DC yield before the inverter, kWh/kWp): south 1,681, east 1,620, west 1,599, north 1,535 at 10°. A survey shading of 8 % on one face of a two-face roof costs 4 % of the station; a 25° tree line to the west costs about 2 %.\n")

pw = HERE / "sites" / "pwa-phase1-sample.json"
if pw.exists():
    rows = json.loads(pw.read_text())
    w("## 5. PWA (กปภ.) stations — survey list\n")
    w("Virtual inverter per station (total AC kW, MAX 125KTL3-X curve). Faces from `tools/yield-reference/data/pwa-faces.csv` (default: one face, 10°, south, no shading — replace with survey data).\n")
    w("| Station | kWp | kW | DC/AC | Faces | GHI | E_Grid (P50) | kWh/kWp | PR | P90 | 25-yr | ERA5 E_Grid |\n|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        w(f"| {r['station']} | {r['dc_kwp']} | {r['ac_kw']} | {r['dc_ac']} | {r.get('faces', 1)} | {r['ghi']} | {r['e_grid_p50']:,} | {r['specific_yield']} | {r['pr']*100:.1f} % | {r['p90_1yr']:,} | {r['lifetime_25y']:,} | {r['e_grid_era5']:,} |")
    tot = lambda k: sum(r[k] for r in rows)
    w(f"| **Total** | **{tot('dc_kwp'):.2f}** | **{tot('ac_kw')}** | | | | **{tot('e_grid_p50'):,}** | | | **{tot('p90_1yr'):,}** | **{tot('lifetime_25y'):,}** | {tot('e_grid_era5'):,} |\n")

w("""## Checks

- **Hour convention:** this engine reproduces PVGIS's east/west/south ratios, and the south total is within 0.05 % of the at-timestamp geometry.
- **Module model:** 570.3 W at STC; NMOT check +0.29 % (package README).
- **Inverter fit:** reproduces η_max to 0.01 pt and η_euro exactly.
- **Regression:** every earlier scenario reproduced exactly after the multi-face refactor (before the hour-convention fix).

## Open inputs

- **Meteo source in PVsyst:** sets ERA5 or GSA as the primary scenario.
- **Component files:** .PAN and .OND files would replace the datasheet fits.
- **Per-station survey:** faces (modules, tilt, compass azimuth), shading %, horizon.
- **Thermal Uc:** confirm the value used in PVsyst.
""")
(HERE / "RESULTS.md").write_text("\n".join(L))
print("written", len(L), "lines")
